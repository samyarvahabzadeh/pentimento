import type { IntentKind, DirectorOutput } from '../core/types.js';

/**
 * Per-node, per-intent authored fallback narratives.
 * These fire ONLY when the LLM service is unavailable.
 * They must NOT change canonical state.
 */
export function getFallbackNarrative(nodeId: string, intentKind: IntentKind | 'generic', playerInput: string = ''): string {
  if (nodeId === 'NODE_00') {
    // Role selection fallback — simply re-present the menu
    return `سه جملهٔ کوتاه روی صفحه بود.
ناشناس، بدون پروفایل.

یک کافه. یک تابلو. یک انتخاب.

برای شروع، نقش خود را انتخاب کن:

۱. مورخ هنری (Art Historian) — عدد ۱
۲. کیمیاگر قهوه (Coffee Alchemist) — عدد ۲
۳. تحلیلگر سیستم (Systems Analyst) — عدد ۳
۴. کارآگاه (Investigator) — عدد ۴`;
  }

  if (nodeId === 'NODE_01') {
    switch (intentKind) {
      case 'speak':
        return 'مرد یک لحظه مکث می‌کند. نگاهش می‌ماند روی تو.';
      case 'observe':
        return 'نور زردرنگ کافه از پشت سرش هاله‌ای ساخته. جزئیات را می‌بینی، اما مطمئن نیستی چه معنایی دارند.';
      case 'physical':
        return 'مرد یک قدم عقب می‌رود. بدنش آماده‌تر از صورتش است.';
      case 'move':
        return 'جابه‌جا می‌شوی. فضای بین شما تغییر می‌کند.';
      case 'threaten':
        return 'لحن‌ات سرد می‌شود. مرد این را می‌فهمد.';
      case 'bluff':
        return 'حرفی می‌زنی. مرد چیزی نمی‌گوید، اما چشمانش حرف می‌زنند.';
      case 'impossible':
        return 'این دنیا چنین کاری نمی‌شناسد. می‌توانی رفتارش را بخوانی — نه ذهنش را.';
      default:
        return 'مرد با همان آرامش به خیابان نگاه می‌کند. هوا سرد است.';
    }
  }

  if (nodeId === 'NODE_02' || nodeId === 'NODE_01_INSIDE') {
    switch (intentKind) {
      case 'speak':
        return 'حانیه دستمال را در دستش جابه‌جا می‌کند و با صدایی ملایم به سوالت پاسخ می‌دهد، در حالی که نگاه مهمان غریبه آرام به فنجان نیمه‌سرد میز ۵ سُر می‌خورد.';
      case 'observe':
        return 'نور زرد کافه روی میز شماره ۵ و لکهٔ قرمز نعلبکی افتاده است. فنجان همچنان دست‌نخورده باقی مانده.';
      case 'move':
        return 'در میان میزهای چوبی قدم برمی‌داری. صدای دستگاه اسپرسو از سمت کانتر شنیده می‌شود.';
      default:
        return 'صدای ملایم موسیقی و آسیاب قهوه در سالن پنتیمنتو ادامه دارد.';
    }
  }

  if (nodeId === 'NODE_03') {
    switch (intentKind) {
      case 'speak':
        return 'یاشین پورتافیلتر را خشک می‌کند و با لحنی شمرده پاسخت را می‌دهد، در حالی که مانی پشت سرش به کارها نظارت می‌کند.';
      case 'observe':
        return 'نور مانیتور POS و سطح استیل دستگاه اسپرسو زیر نور زرد کانتر می‌درخشد.';
      default:
        return 'یاشین و مانی پشت کانتر چوبی آماده‌اند.';
    }
  }

  if (nodeId === 'NODE_04') {
    switch (intentKind) {
      case 'speak':
      case 'observe':
        return 'صدای شدید خروج بخار از نازل اسپرسو (Steam Wand) فضا را پر می‌کند و بخشی از کلمات میان صدا گم می‌شود.';
      default:
        return 'بخار داغ دستگاه اسپرسو در هوای سرد کافه متصاعد می‌شود.';
    }
  }

  if (nodeId === 'NODE_05') {
    switch (intentKind) {
      case 'speak':
      case 'observe':
        return 'یاشین با دقت نمونهٔ دانه‌های قهوه را بو می‌کشد و با اطمینان می‌گوید: «این قدیمیه. نه یعنی مونده نیست. می‌گم روش قدیمیه.»';
      default:
        return 'سینی کاپینگ و دانه‌های رست‌شده روی کانتر قرار دارند.';
    }
  }

  if (nodeId === 'NODE_06') {
    switch (intentKind) {
      case 'observe':
        return 'نور سالن روی سطح تابلو می‌تابد. در نگاه اول و با زاویهٔ روبه‌رو، هیچ ویژگی غیرعادی روی سطح نقاشی به چشم نمی‌آید.';
      case 'speak':
        return 'مانی نگاهی به تابلوی روی دیوار می‌اندازد و نظری کوتاه می‌دهد.';
      case 'physical':
        return 'پیش از اینکه بتوانی چیزی از زیر سطح آشکار کنی، این کار فقط خطر آسیب زدن به تابلو را بالا می‌برد و توجه اطرافیان را جلب می‌کند.';
      default:
        return 'سکوت گالری انتهای سالن کافه پنتیمنتو ادامه دارد.';
    }
  }

  if (nodeId === 'NODE_07') {
    switch (intentKind) {
      case 'observe':
        return 'پشت بوم نقاشی در نور ضعیف دیوار دیده می‌شود. برچسبی قدیمی و کنده شده به چشم می‌خورد که اعداد ۱۴ / ۳ / ۷ / ۵۵ روی آن مانده است.';
      case 'theory':
      case 'speak':
        return 'مانی زانوی دردناکش را مالش می‌دهد و با نگاهی به ساعت مچی‌اش می‌گوید: «چهار تا عدد به تنهایی چیزی رو ثابت نمی‌کنن، ولی ساعت منم همیشه وقتی نباید قاطی می‌کنه.»';
      case 'physical':
        return 'تلاش برای دستکاری یا کندن باقی‌ماندهٔ برچسب فقط خطر از بین رفتن کامل آن و جلب توجه دیگران را به همراه دارد.';
      default:
        return 'پشت تابلوی نقاشی و برچسب کنده شده مقابل شماست.';
    }
  }

  if (nodeId === 'NODE_08') {
    if (/مقایسه|تفاوت|گرد.*و.*خاک|تمیز|غبار/.test(playerInput)) {
      return 'با مقایسه دقیق کارتن‌های خاک‌گرفته روی قفسه‌ها، متوجه می‌شوی یکی از جعبه‌ها به شکل غیرعادی تمیز و عاری از غبار محیط است.';
    }
    switch (intentKind) {
      case 'observe':
        return 'انبار پر از کارتن‌های روی هم چیده شده و بسته‌بندی‌های مختلف است. عطر ملایم دانه‌های قهوه در فضای بسته به مشام می‌رسد.';
      case 'physical':
        return 'جعبه را با احتیاط جابه‌جا می‌کنی؛ بسته‌بندی محکم است و تفاوت اصلی در تمیز بودن سطح آن نسبت به غبار سایر کارتن‌هاست.';
      case 'theory':
      case 'speak':
        return 'تمیزی غیرعادی فقط نشان می‌دهد این جعبه با محیط اطراف همخوان نیست؛ هنوز معلوم نیست چه کسی یا چه زمانی آن را جابه‌جا کرده.';
      default:
        return 'فضای انبار و ردیف کارتن‌ها در سکوت پیش روی شماست.';
    }
  }

  if (nodeId === 'NODE_09') {
    if (/میز.*(هفت|۷)|سیب.*زمینی|مشکوک|تیکت|فیش/.test(playerInput)) {
      return 'فیش سفارش آویزان برای میز ۷ یک سفارش غذای معمولی همراه با سیب‌زمینی اضافه است، بدون هیچ نکته یا پیام رمزآلود.';
    }
    switch (intentKind) {
      case 'speak':
        return 'آرین مهری در حالی که چت‌های گوشی را مدیریت می‌کند با خنده می‌گوید: «آدم‌ها وقتی می‌خوان مسئولیت قبول نکنن ردپاشون رو پاک می‌کنن داداش... درست مثل دستگاهی که نیم ساعت پیش وای‌فای رو قطع کرد و رفت.»';
      case 'observe':
        return 'فضای پرحرارت آشپزخانه با صدای جلزولز ملایم روغن سرخ‌کن، ردیف تخته‌های کار و حرارت اجاق در جریان است. زندگی عادی کافه پنتیمنتو بدون وقفه ادامه دارد.';
      default:
        return 'آشپزخانه با حرارت و صدای سرخ‌کن به کار خود ادامه می‌دهد.';
    }
  }

  if (nodeId === 'NODE_10') {
    if (/بو.*(کنم|می‌کشم|بکشم|می‌کنم)|بوی.*شوینده|شوینده.*متفاوت/.test(playerInput)) {
      return 'با نزدیک شدن به شیء تازه، بوی مادهٔ تمیزکننده‌ای به مشام می‌رسد که با شوینده‌های همیشگی سالن و کافه تفاوت دارد.';
    }
    if (/یاشین.*(بو|نظرت)|بوش.*کن/.test(playerInput)) {
      return 'یاشین با دقت بو می‌کشد و با اطمینان حسی می‌گوید: «این بوی شویندهٔ روتین کافه نیست؛ ترکیبی که ما استفاده می‌کنیم بوی کاملاً متفاوتی داره.»';
    }
    if (/حانیه.*(نظرت|پنتی)|رفتار.*پنتی/.test(playerInput)) {
      return 'خانم محمدی با نگرانی نگاهی به پنتی می‌اندازد و می‌گوید: «امشب اصلاً سمت اون وسیله نمی‌ره... پنتی هیچ‌وقت بی‌دلیل از وسایلش فاصله نمی‌گیره.»';
    }
    if (/مدرک.*نامربوط|نعلبکی|فنجان.*پنتی|کاغذ.*پنتی/.test(playerInput)) {
      return 'پنتی نگاهی بی‌تفاوت به شیء می‌اندازد، خمیازه‌ای می‌کشد و سرش را روی پنجه‌هایش می‌گذارد.';
    }
    if (/نزدیک.*کنم|ببرم.*سمت|زور/.test(playerInput)) {
      return 'وقتی شیء را به پنتی نزدیک می‌کنی، پنتی بدنش را عقب می‌کشد و با قدم‌هایی آرام به گوشهٔ دیگری از پتو می‌رود.';
    }
    switch (intentKind) {
      case 'observe':
        return 'پنتی روی پتوی نرمش لم داده است؛ اما در حرکاتش به وضوح دیده می‌شود که از نزدیک شدن به شیء تازه پرهیز می‌کند و مسیرش را کج می‌کند.';
      case 'theory':
      case 'speak':
        return 'تغییر رفتار پنتی و بوی متفاوت شیء صرفاً نشان‌دهندهٔ یک محرک حسی جدید است؛ هنوز نمی‌توان منشأ مشخصی را به آن نسبت داد.';
      default:
        return 'گوشهٔ دنج پنتی و وسایلش در کنار سالن کافه پنتیمنتو قرار دارند.';
    }
  }

  if (nodeId === 'NODE_11') {
    if (/صالحی.*(نظر|فاکتور|جعل)|جعل.*شده|تحلیل.*جعل/.test(playerInput)) {
      return 'آقای صالحی با نگاهی نافذ به اسناد، نگاهی دقیق به فاکتور می‌اندازد و با لحنی قاطع می‌گوید: «این سند با فرآیند مالی ما همخوان نیست؛ این یک فاکتور ساختگی و جعل‌شده است.»';
    }
    if (/مقایسه|فونت|تفاوت.*(قلم|حروف|چاپ)/.test(playerInput)) {
      return 'با مقایسه این برگه با سربرگ‌های دیگر، متوجه می‌شوی فونت و نحوه چیدمان حروف با تمام فاکتورهای رسمی کافه تفاوت دارد.';
    }
    switch (intentKind) {
      case 'observe':
        return 'فاکتوری در میان اسناد بایگانی دیده می‌شود که روی آن با حروف لاتین چاپ شده است: «R.G. / Lot 55 / Returned».';
      case 'theory':
      case 'speak':
        return 'آقای صالحی در حالی که فاکتورها را مرتب می‌کند، به نکاتی دربارهٔ اسناد اداری اشاره می‌کند.';
      default:
        return 'دفتر حسابداری آقای صالحی و ردیف زونکن‌ها در آرامش و سکوت قرار دارند.';
    }
  }

  if (nodeId === 'NODE_12') {
    if (/مهری.*(نظر|دوربین|لاگ)|لاگ.*(سیستم|دیسک)|هیچ.*وقت.*نوشته|رویداد.*نوشتن/.test(playerInput)) {
      return 'آرین مهری لاگ‌های خام سیستم را روی مانیتور اسکرول می‌کند و با لحنی جدی می‌گوید: «این هفت دقیقه پاک نشده... لاگ‌های دیسک نشون می‌دن دیتا اصلاً از اول روی هارد نوشته نشده.»';
    }
    switch (intentKind) {
      case 'observe':
        return 'روی تایم‌لاین مانیتورهای مداربسته، یک شکاف زمانی هفت دقیقه‌ای دیده می‌شود که در آن هیچ تصویری پخش نمی‌شود.';
      case 'speak':
      case 'theory':
        return 'آرین مهری پشت مانیتورها نشسته و کدهای لاگ سیستم را مرور می‌کند.';
      default:
        return 'نمایشگرهای مداربسته تصاویر زاویه‌های مختلف کافه پنتیمنتو را نشان می‌دهند.';
    }
  }

  if (nodeId === 'NODE_13') {
    if (/موتور|صدای.*موتور/.test(playerInput)) {
      return 'صدای گذرای موتورسیکلتی از چند خیابان دورتر شنیده می‌شود و سپس دوباره سکوت شب کوچه را فرا می‌گیرد.';
    }
    if (/ماشین|خودرو|دومین.*بار/.test(playerInput)) {
      return 'خودرویی که پیش‌تر در اطراف کافه دیده بودی، این بار در حاشیهٔ تاریک کوچه حسینی متوقف است.';
    }
    switch (intentKind) {
      case 'observe':
        return 'هوای خنک شب روی پوستت می‌نشیند و صدای ملایم کافه پشت سرت محو می‌شود. کوچه حسینی در نور زرد چراغ‌ها تاریک و ساکت به نظر می‌رسد.';
      default:
        return 'کوچه حسینی در سکوت شب پیش روی شماست.';
    }
  }

  if (nodeId === 'NODE_14') {
    if (/شیشه|داخل|کابین|صندلی/.test(playerInput)) {
      return 'با دقت خودرو را برانداز می‌کنی؛ جزئیات قابل اتکای تازه‌ای در بررسی به دست نمی‌آید.';
    }
    if (/پلاک/.test(playerInput)) {
      return 'در زاویهٔ تاریک جدول خیابان، پلاک خودرو زیر لایه‌ای از سایه و غبار قرار دارد و اطلاعات مشخصی را نشان نمی‌دهد.';
    }
    if (/بشکنم|باز.*کنم|دستگیره|قفل/.test(playerInput)) {
      return 'دست بردن به دستگیره یا تلاش برای باز کردن در فقط صدای فلز را در کوچه خلوت پخش می‌کند و نگاه‌های ناخواسته را متوجه شما می‌سازد.';
    }
    if (/گرشاسبی|صالحی|مهری|مانی/.test(playerInput)) {
      return 'آرین گرشاسبی نگاهی به خودرو می‌اندازد و می‌گوید: «ماشین چند دقیقه‌ای هست اینجاست، ولی ندیدم کسی ازش پیاده یا سوار بشه.»';
    }
    switch (intentKind) {
      case 'observe':
        return 'خودروی متوقف در حاشیهٔ جدول خاموش و بی‌صداست و هیچ علامتی از فعالیت درون آن دیده نمی‌شود.';
      default:
        return 'خودروی پارک‌شده در کنار جدول کوچه حسینی خاموش و بی‌حرکت باقی مانده است.';
    }
  }

  if (nodeId === 'NODE_15') {
    if (/دروغ|دروغگو/.test(playerInput)) {
      return 'نگاهش کمی جمع می‌شود و در مقام دفاع می‌گوید: «چرا باید دروغ بگم؟ من چیزی که با چشم خودم دیدم رو می‌گم.»';
    }
    if (/ساعت|زمان|مبنا|تایمینگ/.test(playerInput)) {
      return 'وقتی دربارهٔ زمان دقیق خروج می‌پرسی، متوجه می‌شوی مراجع زمانی و ساعت‌های مورد استناد دو شاهد با یکدیگر همخوانی ندارند.';
    }
    if (/پشتی|حیاط|انبار/.test(playerInput)) {
      return 'با لحنی مطمئن تأکید می‌کند که مرد از انبار رد شد و از درب پشتی و حیاط خارج شد.';
    }
    if (/اصلی|خیابان|جلوی.*چشم/.test(playerInput)) {
      return 'با اطمینان می‌گوید که مرد مستقیماً از درب اصلی کافه خارج شد و وارد خیابان شد.';
    }
    switch (intentKind) {
      case 'speak':
      case 'theory':
        return 'روایت‌های شاهدان دربارهٔ مسیر خروج مرد با یکدیگر دچار تناقض کامل است.';
      default:
        return 'سالن کافه پنتیمنتو در سکوت و آرامش شبانه قرار دارد.';
    }
  }

  if (nodeId === 'NODE_16') {
    if (/قبول|می‌پذیرم|معامله.*(می‌کنم|کنیم)|توافق.*مالی.*قبول/.test(playerInput)) {
      return 'طرف مقابل با لبخندی کنترل‌شده سری تکان می‌دهد: «تصمیم هوشمندانه‌ای گرفتید، آقای صالحی؛ این پرونده همین‌جا به پایان می‌رسه.»';
    }
    if (/رد.*(می‌کنم|کنیم)|قبول.*نمی|هیچ.*معامله‌ای|پولتون.*رو.*نمی/.test(playerInput)) {
      return 'طرف مقابل بدون کوچک‌ترین تغییر در لحنش فنجان را کنار می‌گذارد: «امیدوارم بعداً از انتخابتون پشیمون نشید، آقای صالحی.»';
    }
    if (/سکوت|\.\.\.|چیزی.*نمی‌گم|حرفی.*نمی/.test(playerInput)) {
      return 'سکوت سنگینی میان میز برقرار می‌شود. طرف مقابل پس از مکثی آرام می‌گوید: «سکوت شما رو درک می‌کنم، اما شاید یک توافق مالی بی‌دردسر راه‌حل بهتری باشه.»';
    }
    if (/بلوف|فروختیم|دست.*ماست|پلیس|شکایت/.test(playerInput)) {
      return 'طرف مقابل برای کسری از ثانیه مکث می‌کند و سپس با خونسردی لحنش را حفظ کرده، گفتگو را کنترل می‌نماید.';
    }
    if (/چی.*می‌خواید|هدفتون|چرا.*اینجا|منظورتون|خواسته/.test(playerInput)) {
      return 'طرف مقابل نگاهی آرام به آقای صالحی می‌اندازد و با لحنی شمرده می‌گوید: «می‌خواهیم چیزی که هیچ‌وقت مال شما نبوده، مال شما باقی نماند.»';
    }
    switch (intentKind) {
      case 'observe':
        return 'طرف مقابل با کت و شلوار مرتب، دستانی آرام روی میز و نگاهی سرد و مؤدب به شما چشم دوخته است.';
      case 'speak':
      case 'theory':
        return 'طرف مقابل با لحنی ملایم و کنترل‌شده می‌گوید: «ما نمی‌خواهیم چیزی از شما بگیریم، آقای صالحی.»';
      default:
        return 'میز ملاقات در سکوت محیط عمومی قرار دارد.';
    }
  }

  if (nodeId === 'NODE_17') {
    if (/خودت.*(مرتب|حل).*کن|همه.*رو.*بچین|جواب.*رو.*بگو/.test(playerInput)) {
      return 'تلفیق نهایی نیازمند تصمیم‌گیری شماست؛ کدام دو مدرک را مایلید ابتدا در محور زمانی مقایسه کنید؟';
    }
    if (/صالحی.*(نظر|کمک)|کمک.*صالحی/.test(playerInput)) {
      return 'آقای صالحی به صندلی تکیه می‌دهد و می‌گوید: «از منظر اسناد مالی، فاکتور تا قبل از قرار گرفتن در بایگانی وجود خارجی نداشته است.»';
    }
    if (/یاشین.*(نظر|کمک)|کمک.*یاشین/.test(playerInput)) {
      return 'یاشین دست به چانه می‌زند: «عطر و اصالت قهوه تابع زمانه، اما فرآیند رست باید قبل از بسته‌بندی نهایی رخ داده باشه.»';
    }
    if (/مهری.*(نظر|کمک)|کمک.*مهری/.test(playerInput)) {
      return 'آرین مهری به لاگ‌های سیستم اشاره می‌کند: «چیزی که روی دیسک ثبت نشده یعنی قبل از اینکه سرویس بخواد بنویسه مسدود یا قطع بوده.»';
    }
    if (/پس.*می‌گیرم|اشتباه.*فکر.*می‌کردم|نظرم.*عوض.*شد/.test(playerInput)) {
      return 'فرضیهٔ پیشین بازنگری و از روی تختهٔ فرضیات برداشته می‌شود؛ نگاه به پرونده با شواهد تازه بازسازی می‌گردد.';
    }
    if (/وصل|پیوند|ارتباط/.test(playerInput)) {
      return 'پیوند میان دو مدرک با دقت بررسی و روی برد ثبت می‌شود؛ ارتباط‌ها به تدریج پررنگ‌تر می‌شوند.';
    }
    if (/قبل|بعد|همزمان|پیش.*از|پس.*از|تایم‌لاین|ترتیب/.test(playerInput)) {
      return 'رابطهٔ زمانی میان شواهد روی تخته تنظیم می‌شود؛ تقدم و تأخر وقایع شکل مشخص‌تری به خود می‌گیرد.';
    }
    if (/نهایی|ثبت.*نهایی|جمعبندی|جمع‌بندی/.test(playerInput)) {
      return 'محور زمانی شواهد نهایی و انسجام آن در پرونده تثبیت می‌شود.';
    }
    switch (intentKind) {
      case 'observe':
        return 'شواهد و سرنخ‌های کشف‌شده روی میز کار در برابرت چیده شده‌اند؛ آمادهٔ برقراری پیوندهای منطقی و تعیین تقدم و تأخر زمانی.';
      default:
        return 'میز کار آرشیو و پروندهٔ پنتیمنتو در انتظار بررسی شماست.';
    }
  }

  if (nodeId === 'NODE_18') {
    if (/نقشه|کجا|مخفی|گنج/.test(playerInput)) {
      return '«نقشه نبود... هیچ‌وقت نقشه نبود. همه دنبال جایی بودن که دانه‌ها مخفی شدن، اما این فقط زنجیرهٔ مالکیت رو نشون می‌ده.»';
    }
    if (/۵۵|پلاک|کافه|نتیجه|نهایی/.test(playerInput)) {
      return 'تصویر آخر برگردانده می‌شود. در پشت آن، عدد ۵۵ با وضوح نمایان است؛ پلاک کافه پنتیمنتو. پایان زنجیره.';
    }
    if (/لایه‌ها|زیرین|روی.*هم|چهار/.test(playerInput)) {
      return 'چهار لایهٔ زیرین نقاشی روی هم قرار می‌گیرند: دست، پنجره، فنجان و سایه. سیر تاریخی اثر لایه‌به‌لایه آشکار می‌شود.';
    }
    switch (intentKind) {
      case 'observe':
        return 'سالن کافه در نور ملایم گرگ‌ومیش صبح غرق در سکوت است. نگاه اعضای کافه به لایه‌های چیده‌شدهٔ تابلو دوخته شده است.';
      case 'speak':
        return 'سالار در سکوت به آخرین تصویر نگاه می‌کند و منتظر جمع‌بندی نهایی توست.';
      default:
        return 'لحظهٔ پایان و نتیجه‌گیری نهایی پنتیمنتو فرارسیده است.';
    }
  }

  return 'صحنه ادامه دارد.';
}

function detectFallbackIntent(input: string): IntentKind {
  const t = input;
  if (/ذهن.*(خوند|بخون|می.?خون|میخون)|تله.?پاتی|نامرئی|زمان.*متوقف|فراطبیعی|جادو/.test(t)) return 'impossible';
  if (/مشت|هل\s|هلش|ضربه|کتک|بزنم|بزنمش|حمله/.test(t)) return 'physical';
  if (/تهدید|می‌کشم|خطر.*بده/.test(t)) return 'threaten';
  if (/وانمود|بلوف|دروغ.*بگم|جعل/.test(t)) return 'bluff';
  if (/نگاه.*کن|نگاه.*کردم|نگاه.*می|بررسی|ببینم|مشاهده|فنجان|نعلبکی|میز|دستگاه|دانه|رست|نازل/.test(t)) return 'observe';
  if (/وارد|دنبالش|می‌رم|میرم|قدم|کافه.*برم|راه.*می‌افت|کانتر|گالری/.test(t)) return 'move';
  if (/اسم|سلام|بپرسم|بپرسی|می‌پرسم|می‌گم|میگم|چرا\s|کجا\s|حانیه|یاشین|مانی|بگو|کی بود/.test(t)) return 'speak';
  if (/فکر.*می‌کنم|شاید\s|احتمال|نظریه/.test(t)) return 'theory';

  return 'other';
}

export function createFallbackOutput(nodeId: string, input: string): DirectorOutput {
  const intentKind = detectFallbackIntent(input);

  const targetId = (nodeId === 'NODE_03' || nodeId === 'NODE_04' || nodeId === 'NODE_05')
    ? 'yashin'
    : (nodeId === 'NODE_02' ? 'haniyeh' : 'exiting_man');

  return {
    version: 1,
    narrative: getFallbackNarrative(nodeId, intentKind, input),
    interpretation: {
      kind: intentKind,
      targetId,
      intentSummary: `Fallback: ${intentKind}`,
    },
    softEffects: [],
    memoryCandidates: [],
    referencedFactIds: [],
  };
}
