import type { CandidateAction, PlayerClassId, RunState, TurnResolution } from './types.js';
import { getRoleProfile } from '../canon/roleProfiles.js';
import { getLoopEcho } from '../canon/loopEchoes.js';

export interface RenderNarrativeOptions {
  state: RunState;
  resolution: TurnResolution;
  playerInput: string;
  candidate?: CandidateAction;
}

export function renderNarrative(options: RenderNarrativeOptions): string {
  const { state, resolution, playerInput, candidate } = options;
  const role = state.canonical.playerClass ?? 'art_historian';
  const roleProfile = getRoleProfile(role);
  const candidateId = resolution.interpreted.candidateId;

  // 1. Authored Peaks & Endings
  if (resolution.endingId) {
    return renderEndingNarrative(resolution.endingId, state);
  }

  // 2. Emergent Prose if present on candidate
  if (candidate?.emergentProse) {
    return candidate.emergentProse;
  }

  // 2. Authored Peak candidate matches
  switch (candidateId) {
    case 'SELECT_ROLE_ART_HISTORIAN':
      return `با تخصص «مورخ هنری»، قدم به کوچهٔ حسینی می‌گذاری. چشمانت بی‌اختیار به تناسبات قاب، بافت لایه‌ها و سایه‌روشن‌های تاریخی جلب می‌شود.\n\nروبروی کافه پنتیمنتو ایستاده‌ای. ساعت ۰۰:۱۷ نیمه‌شب است. باران به آرامی سنگ‌فرش را خیس می‌کند و درِ شیشه‌ای کافه تکان می‌خورد.`;

    case 'SELECT_ROLE_COFFEE_ALCHEMIST':
      return `با لنز حسی «کیمیاگر قهوه»، وارد محدودهٔ پنتیمنتو می‌شوی. هوای مرطوب عظیمیه با عطر دورِ رُست تیره و بوی چوب خیس درآمیخته؛ از پشت در بسته نمی‌توان منشأ بوهای داخل کافه را تشخیص داد.\n\nساعت ۰۰:۱۷ است. مردی با پالتوی تیره و دستکش چرمی قرمز رنگ با شتاب از در خارج می‌شود.`;

    case 'SELECT_ROLE_SYSTEMS_ANALYST':
      return `با ذهن ساختاریافتهٔ «تحلیل‌گر سیستم‌ها»، نگاهت به ساعت گوشی و دوربین بالای ورودی می‌افتد. ساعت ۰۰:۱۷:۴۳ است؛ برای یافتن هر ناهماهنگی باید بعداً رکوردهای مستقل صندوق و دوربین را با هم مقایسه کنی.\n\nمردی با دستکش چرمی قرمز رنگ از ورودی کافه بیرون می‌آید.`;

    case 'SELECT_ROLE_INVESTIGATOR':
      return `با نگاه تیزبین «کارآگاه اجتماعی»، مکث حساب‌شدهٔ مرد پالتوپوش و نحوهٔ نگه‌داشتن لنگهٔ در با دستکش قرمز را زیر نظر می‌گیری؛ رفتارش کنترل‌شده است، اما هنوز چیزی دربارهٔ قصدش ثابت نمی‌کند.\n\nساعت ۰۰:۱۷ نیمه‌شب است. درِ کافه هنوز روی پاشنه آرام نگرفته که او در تاریکی کوچه ناپدید می‌شود.`;

    case 'ENTER_CAFE':
      return `دستگیرهٔ برنجی را فشار می‌دهی و پا به گرمای سالن کافه پنتیمنتو می‌گذاری.
در گوشهٔ سالن، میز شماره ۵ با یک فنجان اسپرسوی دست‌نخورده رها شده و حانیه با تبلت در دست کنار میز ایستاده است. پنتی (بچه‌گربهٔ کافه) گوشه‌ای کز کرده و در انتهای سالن، یاشین و مانی پشت پیشخوان چوبی حضور دارند.`;

    case 'OBSERVE_EXITING_MAN':
      return `برای چند ثانیه به قامت مرد پالتوپوش دقیق می‌شوی. دستکش چرمی قرمز رنگی که در دست راست دارد زیادی تمیز و بدون انعطاف است؛ انگار نه برای سرما، بلکه برای دست نزدن مستقیم به اشیاء پوشیده شده است.
او بدون تماس چشمی به سمت کوچه حسینی گام برمی‌دارد.`;

    case 'EXAMINE_WET_RECEIPT': {
      let roleLens = '';
      if (role === 'systems_analyst') {
        roleLens = '\n[لنز سیستم‌ها]: تایم‌استمپ فیش ساعت ۰۰:۱۷ را نشان می‌دهد؛ انطباق صددرصدی با لحظه خروج مرد.';
      } else if (role === 'art_historian') {
        roleLens = '\n[لنز هنر]: مهر کم‌رنگ چهارگوش در حاشیهٔ کاغذ نشانه‌هایی شبیه به نشان کارگاهی دارد.';
      }
      return `روی سنگ‌فرش سرد کوچه خم می‌شوی و برگهٔ کاغذی خیس را برمی‌داری.
یک فیش سفارش با مبلغ و ساعت دقیق ۰۰:۱۷ است که گوشه‌اش لکهٔ جوهر عجیبی دارد.${roleLens}`;
    }

    case 'EXAMINE_TABLE_5': {
      let chemInsight = '';
      if (role === 'coffee_alchemist') {
        chemInsight = '\n[لنز کیمیاگر]: بوی بلندشده از لبهٔ فنجان بوی روغن دانه نیست؛ یک حلال هیدروکربنی بسیار غلیظ است.';
      }
      return `به میز شماره ۵ نزدیک می‌شوی. فنجان سرامیکی کرم‌رنگ روی نعلبکی قرار دارد و مایع تیرهٔ درونش هنوز ولرم است. رد یک لکهٔ قرمز براق نیز روی گوشهٔ میز دیده می‌شود.${chemInsight}`;
    }

    case 'EXAMINE_ESPRESSO_CUP_SMELL':
      return `فنجان را با احتیاط بالا می‌آوری و بو می‌کنی.
بوی تند و نفتی یک حلال شیمیایی مشامت را می‌زند. این ماده برای پاک‌کردن سریع لایه‌های رنگ یا محو کردن اثر انگشت به کار می‌رود؛ نه دم‌آوری قهوه!`;

    case 'TALK_TO_HANIYEH':
      return `حانیه سرش را از روی تبلت بالا می‌آورد و نفس عمیقی می‌کشد:
«اون آقاهه حتی یک قلوپ هم از قهوه‌اش نخورد... فقط فنجون رو بو کرد و بعد با عجله بلند شد. پنتی هم از همون موقع رفته زیر مبل قایم شده.»`;

    case 'APPROACH_COUNTER':
      return `کنار پیشخوان چوبی صیقلی کافه می‌ایستی. یاشین با پیراهن آراسته در حال خشک کردن فنجان‌هاست و مانی دستمال ضخیمی را روی نازل بخار دستگاه اسپرسو حرکت می‌دهد. هر دو متوجه حضورت می‌شوند.`;

    case 'TALK_TO_YASHIN':
      return `یاشین دست از کار می‌کشد و با لبخندی کنترل‌شده می‌گوید:
«درود. اگر دنبال میز پنج هستید، اون مهمان درست ساعت ۰۰:۱۷ رفت. حتی فیش سفارش رو هم از روی کانتر برداشت اما نمی‌دونم چرا فنجونش رو رها کرد.»`;

    case 'TALK_TO_MANI_ABOUT_CUP': {
      const trust = state.npcTrust?.mani ?? 0;
      if (trust >= 1 || role === 'coffee_alchemist') {
        return `مانی با صدای بم خود آرام می‌گوید:
«این بوی پودر رسوب‌زدای دستگاه نیست. من سال‌ها تو ارومیه بار کار کردم؛ این بوی تینر فرّاره که تو کارگاه‌های مرمت بوم می‌زنن تا رنگ تازه رو بخوابونن.»`;
      }
      return `مانی نگاهی به فنجان می‌اندازد: «اسپرسوی معمولیه. شاید نازل کمی حرارت اضافه داده باشه.»`;
    }

    case 'INSULT_MANI_COFFEE':
      return `مانی اخم‌هایش را در هم می‌کشد و دستمال را محکم روی میز می‌گذارد:
«اگر فکر کردی قهوه درست کردن تو این سرما شوخیه، اشتباه اومدی رفیق. اینجا هیچ‌چیز کثیف یا خراب نیست.»`;

    case 'EXAMINE_PAINTING_SURFACE': {
      return `روبروی تابلوی دیواری می‌ایستی و نور زاویه‌دار به سطح بوم می‌تابانی.
زیر لایهٔ شفاف روغن، بافت برجسته‌ای دیده می‌شود که با خطوط رویی تصویر هم‌خوانی ندارد؛ یک لایهٔ مخفی در زیر رنگ (Pentimento) وجود دارد که با مهارت پوشانده شده است.`;
    }

    case 'CHECK_POS_ORDERS':
      return `صفحهٔ مانیتور پوز و لاگ سفارش‌ها را بازبینی می‌کنی.
فیش سفارش شمارهٔ ۵۵ در ساعت ۰۰:۱۷:۲۲ ثبت شده، اما فاکتور دست‌نویس مهرشده ساعت ۰۰:۱۰ را نشان می‌دهد؛ یک گسست زمانی هفت‌دقیقه‌ای در سیستم وجود دارد.`;

    case 'BLUFF_COLLECTOR_WITH_EVIDENCE':
      return `با اطمینان به کلکسیونر خیره می‌شوی و تناقض‌های فاکتور و لایه‌های نقاشی را روی میز می‌کوبی.
کلکسیونر برای چند لحظه سکوت می‌کند، لبخندش محو می‌شود و لحنش تغییر می‌کند: «به نظر می‌رسه مدارک بیشتری از اونچه فکر می‌کردم در دست دارید...»`;

    case 'PROCEED_TO_ARCHIVE_SYNTHESIS':
      return `پس از روشن‌شدن انگیزهٔ خریدار، مدارک را از گفت‌وگو جدا می‌کنی و روی میز آرشیو می‌چینی. فقط شواهدی که واقعاً کشف کرده‌ای وارد خط زمانی می‌شوند.`;

    case 'SUBMIT_ARCHIVE_SYNTHESIS':
      return `چهار رشته را بدون پرش به هم وصل می‌کنی: ثبت نقدی ۰۰:۱۱، رسید چاپ‌شدهٔ ۰۰:۱۷، فاکتور جعلی Lot 55 و برچسب انتقال 14/3/7/55.
این جمع‌بندی نحوهٔ دستکاری پروندهٔ امشب را توضیح می‌دهد و اجازه می‌دهد لایهٔ تاریخی تابلو را بدون تکیه بر حدس بررسی کنی.`;

    case 'INSPECT_BEHIND_PAINTING':
      return `تابلو را با احتیاط کمی از دیوار فاصله می‌دهی و به پشت بوم نگاه می‌کنی.
برچسب مالکیت کهنه و نیمه‌کنده‌ای پشت قاب دیده می‌شود. بخشی از نوشته زیر پارگی و گردوغبار پنهان است؛ برای خواندن اعداد باید خود برچسب را جداگانه بررسی کنی.`;

    case 'EXAMINE_PENTI':
      return `پنتی زیر صندلی کز کرده، گوش‌هایش عقب رفته و از میز پنج و فنجان قهوه فاصله نگه داشته است.`;

    case 'APPROACH_GALLERY':
      return `به سمت انتهای سالن و دیوار گالری حرکت می‌کنی. تابلوی نقاشی پنتیمنتو در پرتو ملایم هالوژن‌های دیواری در برابرت قرار می‌گیرد.`;

    case 'APPROACH_OFFICE':
      return `وارد اتاق حسابداری می‌شوی. سالار صالحی پشت میز کار چوبی نشسته و با چهره‌ای مضطرب اسناد را وارسی می‌کند.`;

    case 'APPROACH_STORAGE':
      return `به سمت انبار کارتن‌ها و بسته‌های بسته‌بندی در انتهای راهرو می‌روی.`;

    case 'CONFRONT_SALAR_EVIDENCE':
      return `تناقض ساعت فاکتور، مهر چهارگوش و لایهٔ مخفی پنتیمنتو را روی میز سالار قرار می‌دهی.\nسالار برای لحظه‌ای جا می‌خورد، عینکش را برمی‌دارد و با صدای آهسته می‌گوید: «پس فهمیدی... این فقط یک تابلو نیست؛ امشب باید تکلیف این لایه‌های پنهان روشن بشه.»`;

    case 'EXAMINE_OFFICE_LEDGER':
      return `زونکن خاکستری را روی میز سالار باز می‌کنی. فاکتور مربوط به پلاک ۵۵ و بستهٔ سفارشی دارای مهری با چهار نماد است: دست، پنجره، فنجان و سایه.`;

    case 'action_observe_surroundings':
    case 'action_look_around_general':
      return `نگاهی دقیق به فضای اطراف می‌اندازی. نور ملایم چراغ‌ها، صدای ضعیف نم‌نم باران پشت پنجره و بوی قهوه سالن را در سکوتی محتاطانه نگه داشته‌اند.`;

    case 'REVEAL_HISTORICAL_BREACH_FLORENCE':
      return `نور مایل را روی زیرسازی بوم و حاشیهٔ سند نگه می‌داری. چهار نشانه—دست، پنجره، فنجان و سایه—کنار چهار نام کارگاهی تکرار شده‌اند؛ نه مثل امضای مالک، مثل ثبت کسانی که یک انتقال ممنوع را دیده‌اند.

زیر رنگ قهوه‌ایِ لایهٔ رویی، جای نام پنجمی عمداً تراشیده شده است. خود تابلو دفتر شاهدان بوده: پاسداران آن را زیر تصویر تازه پنهان کرده‌اند، متولیان زنجیره‌اش را خصوصی نگه داشته‌اند و ویراستاران قرن‌ها کوشیده‌اند نام حذف‌شده را برای همیشه محو کنند.

پلاک ۵۵ آخرین حلقه است، نه مقصد یک گنج. ماجرای امشب تکرار همان پرسش قدیمی است: حقیقت را چه کسی حق دارد نگه دارد—و به چه قیمتی؟`;

    default:
      if (candidate?.emergentProse) {
        return candidate.emergentProse;
      }
      return `با دقت فضا را بررسی می‌کنی و نشانه‌های موجود را زیر نظر می‌گیری.`;
  }
}

function renderEndingNarrative(endingId: string, state: RunState): string {
  switch (endingId) {
    case 'BAD_ENDING_ABANDONMENT_ARSON': {
      const echo = getLoopEcho('ECHO_AFTER_ABANDON');
      return `【پایان تلخ: رها کردن پرونده و خاکستر نیمه‌شب】\n\nکافه را به حال خود رها می‌کنی و به خانه برمی‌گردی تا بخوابی.
صبح با صدای تماس‌های مکرر و بوق ممتد گوشی بیدار می‌شوی. خبر آتش‌سوزی شبانه کافه پنتیمنتو و نابودی تابلو در کانال‌های محلی پیچیده است. شواهد برای همیشه سوختند.\n\n💡 [پژواک لوپ]: ${echo?.hint ?? ''}`;
    }

    case 'BAD_ENDING_TOXIC_SHOCK': {
      const echo = getLoopEcho('ECHO_TOXIC_SHOCK');
      return `【پایان تلخ: بلعیدن حلال صنعتی و شوک تنفسی】\n\nمایع تلخ و سوزاننده گلویت را می‌سوزاند. ثانیه‌هایی بعد دنیا تیره و تار می‌شود و صدای فریاد حانیه آخرین چیزی است که به گوشت می‌رسد.\n\n💡 [پژواک لوپ]: ${echo?.hint ?? ''}`;
    }

    case 'BAD_ENDING_SYNDICATE_ABDUCTION': {
      const echo = getLoopEcho('ECHO_CHASE_ABDUCTION');
      return `【پایان تلخ: کمین شبانه در کوچه حسینی】\n\nدویدن بدون نقشه در کوچه‌های تاریک عظیمیه به کمین یک ون تیره ختم می‌شود. قبل از اینکه بتوانی فریاد بزنی، درها باز و بسته می‌شوند.\n\n💡 [پژواک لوپ]: ${echo?.hint ?? ''}`;
    }

    case 'BAD_ENDING_INTERNAL_BETRAYAL': {
      const echo = getLoopEcho('ECHO_FALSE_ACCUSATION');
      return `【پایان تلخ: فروپاشی اعتماد و شکاف درونی】\n\nاتهامات تند و بی‌اساس به پرسنل، سالن کافه را به میدان نزاع تبدیل کرد. در این هرج‌ومرج، فرد نفوذی فرصت یافت تا مدارک اصلی را خارج کند.\n\n💡 [پژواک لوپ]: ${echo?.hint ?? ''}`;
    }

    case 'BAD_ENDING_POLICE_SHUTDOWN': {
      const echo = getLoopEcho('ECHO_VIOLENCE_SHUTDOWN');
      return `【پایان تلخ: مداخله پلیس و پلمب صحنه】\n\nدرگیری و تنش بالا باعث تماس همسایه‌ها با پلیس شد. درهای کافه پلمب شد و فرصت بررسی مدارک قبل از نابودی از دست رفت.\n\n💡 [پژواک لوپ]: ${echo?.hint ?? ''}`;
    }

    case 'TRUE_ENDING':
      return `【پایان راستین: پرده‌برداری از دستکش قرمز و رخنهٔ تاریخی】\n\nتو نه‌تنها نقشهٔ انتقال تابلوی پلاک ۵۵ و ترفندهای خریدار را خنثی کردی، بلکه پرده از سند باستانی کارگاه فلورانس برداشتی.
پروندهٔ امشب کافه بسته شد، اما راز دستکش‌های قرمز تازه آغاز شده است...`;

    case 'GOOD_ENDING':
      return `【پایان موفقیت‌آمیز: حل پروندهٔ کافه پنتیمنتو】\n\nزنجیرهٔ دستکاری اسناد و نقش خریدار پلاک ۵۵ اثبات شد و از سرقت تابلو جلوگیری کردی. آرامش به کافه بازگشت.`;

    default:
      return `【پایان پرونده】\n\nتحقیقات امشب در کافه پنتیمنتو به نتیجه رسید.`;
  }
}
